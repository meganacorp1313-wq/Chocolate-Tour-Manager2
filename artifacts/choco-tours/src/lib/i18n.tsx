const dateLocales = {
  es,
  en: enUS,
  ru
};

interface I18nContextType {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string) => string;
  dateLocale: Locale;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    const saved = localStorage.getItem('choco-lang');
    return (saved as Language) || 'es';
  });

  useEffect(() => {
    localStorage.setItem('choco-lang', lang);
  }, [lang]);

  const t = (key: string) => dictionaries[lang][key] || dictionaries['es'][key] || key;
  const dateLocale = dateLocales[lang];

  return (
    <I18nContext.Provider value={{ lang, setLang: setLangState, t, dateLocale }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
